class AudioEngine {
    constructor() {
        this.ctx = null; this.masterGain = null; this.ambientGain = null;
        this.droneOsc = null; this.noiseNode = null; this.lpf = null; this.dist = null; 
        this.isInitialized = false; this.volMaster = 0.7; this.volAmbient = 0.8;
    }
    init() {
        if (this.isInitialized) return;
        this.ctx = new (window.AudioContext || window.webkitAudioContext)();
        this.masterGain = this.ctx.createGain(); this.masterGain.gain.value = this.volMaster; this.masterGain.connect(this.ctx.destination);
        this.dist = this.ctx.createWaveShaper(); this.dist.curve = this.makeDistortionCurve(0); this.dist.oversample = '4x'; this.dist.connect(this.masterGain);
        this.ambientGain = this.ctx.createGain(); this.ambientGain.gain.value = this.volAmbient; this.ambientGain.connect(this.dist);
        
        this.droneOsc = this.ctx.createOscillator(); this.droneOsc.type = 'sawtooth'; this.droneOsc.frequency.value = 35;
        this.lpf = this.ctx.createBiquadFilter(); this.lpf.type = 'lowpass'; this.lpf.frequency.value = 200;
        const droneVol = this.ctx.createGain(); droneVol.gain.value = 0; this.droneGainRef = droneVol; 
        this.droneOsc.connect(this.lpf).connect(droneVol).connect(this.ambientGain); this.droneOsc.start();

        const bufferSize = this.ctx.sampleRate * 2; const buffer = this.ctx.createBuffer(1, bufferSize, this.ctx.sampleRate);
        const data = buffer.getChannelData(0); for (let i = 0; i < bufferSize; i++) data[i] = Math.random() * 2 - 1;
        this.noiseNode = this.ctx.createBufferSource(); this.noiseNode.buffer = buffer; this.noiseNode.loop = true;
        const noiseLpf = this.ctx.createBiquadFilter(); noiseLpf.type = 'lowpass'; noiseLpf.frequency.value = 800;
        const noiseVol = this.ctx.createGain(); noiseVol.gain.value = 0; this.noiseGainRef = noiseVol;
        this.noiseNode.connect(noiseLpf).connect(noiseVol).connect(this.ambientGain); this.noiseNode.start();
        this.isInitialized = true;
    }
    makeDistortionCurve(amount) {
        const k = typeof amount === 'number' ? amount : 50, n_samples = 44100, curve = new Float32Array(n_samples), deg = Math.PI / 180;
        for (let i = 0; i < n_samples; ++i) { const x = i * 2 / n_samples - 1; curve[i] = (3 + k) * x * 20 * deg / (Math.PI + k * Math.abs(x)); }
        return curve;
    }
    setMasterVol(val) { this.volMaster = val / 100; if(this.masterGain) this.masterGain.gain.value = this.volMaster; }
    setAmbientVol(val) { this.volAmbient = val / 100; if(this.ambientGain) this.ambientGain.gain.value = this.volAmbient; }
    setAmbientState(droneVol, droneFreq, noiseVol, transition = 2, distAmount = 0) {
        if (!this.isInitialized) return; const now = this.ctx.currentTime;
        this.droneGainRef.gain.linearRampToValueAtTime(droneVol, now + transition); this.droneOsc.frequency.linearRampToValueAtTime(droneFreq, now + transition);
        this.noiseGainRef.gain.linearRampToValueAtTime(noiseVol, now + transition); this.dist.curve = this.makeDistortionCurve(distAmount);
        if (droneVol > 0.1) this.lpf.frequency.linearRampToValueAtTime(800, now + transition); else this.lpf.frequency.linearRampToValueAtTime(200, now + transition);
    }
    playClick() {
        if (!this.isInitialized) return; const osc = this.ctx.createOscillator(); const gain = this.ctx.createGain();
        osc.type = 'sine'; osc.frequency.setValueAtTime(900, this.ctx.currentTime); osc.frequency.exponentialRampToValueAtTime(100, this.ctx.currentTime + 0.05);
        gain.gain.setValueAtTime(0.3, this.ctx.currentTime); gain.gain.exponentialRampToValueAtTime(0.01, this.ctx.currentTime + 0.05);
        osc.connect(gain).connect(this.masterGain); osc.start(); osc.stop(this.ctx.currentTime + 0.05);
    }
    playGlitch() {
        if (!this.isInitialized) return; const osc = this.ctx.createOscillator(); const gain = this.ctx.createGain();
        osc.type = 'square'; osc.frequency.setValueAtTime(100 + Math.random() * 1000, this.ctx.currentTime); osc.frequency.exponentialRampToValueAtTime(40, this.ctx.currentTime + 0.15);
        gain.gain.setValueAtTime(0.5, this.ctx.currentTime); gain.gain.exponentialRampToValueAtTime(0.01, this.ctx.currentTime + 0.15);
        osc.connect(gain).connect(this.masterGain); osc.start(); osc.stop(this.ctx.currentTime + 0.15);
    }
    playError() {
        if (!this.isInitialized) return; const osc = this.ctx.createOscillator(); const gain = this.ctx.createGain();
        osc.type = 'sawtooth'; osc.frequency.setValueAtTime(150, this.ctx.currentTime); osc.frequency.setValueAtTime(100, this.ctx.currentTime + 0.1);
        gain.gain.setValueAtTime(0.4, this.ctx.currentTime); gain.gain.linearRampToValueAtTime(0, this.ctx.currentTime + 0.3);
        osc.connect(gain).connect(this.masterGain); osc.start(); osc.stop(this.ctx.currentTime + 0.3);
    }
    stopAll(transition = 1) {
        if (!this.isInitialized) return; const now = this.ctx.currentTime;
        this.droneGainRef.gain.linearRampToValueAtTime(0, now + transition); this.noiseGainRef.gain.linearRampToValueAtTime(0, now + transition);
    }
}
