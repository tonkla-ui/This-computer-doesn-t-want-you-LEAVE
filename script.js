class OSEngine {
    constructor() {
        this.container = document.getElementById('window-manager'); this.taskbar = document.getElementById('taskbar-processes');
        this.zIndex = 20; this.windows = new Map(); this.dragState = { win: null, offsetX: 0, offsetY: 0 }; this.termElement = null;
        this.initClock(); this.bindEvents();
    }

    initClock() { setInterval(() => { const c = document.getElementById('taskbar-clock'); if(c) c.innerText = new Date().toLocaleTimeString([], {hour: '2-digit', minute:'2-digit'}); }, 1000); }

    bindEvents() {
        // 1. ระบบกดเปิดไอคอน (แยก PC และ มือถือ ให้กดติด 100%)
        document.querySelectorAll('.desktop-icon').forEach(icon => {
            let lastTap = 0;
            
            const triggerApp = (app) => {
                audio.playClick(); 
                if(app === 'readme') this.spawnReadme(); 
                if(app === 'logs') this.spawnLogs();
                if(app === 'terminal') this.spawnTerminal(); 
                if(app === 'trash') this.spawnTrash();
            };

            // สำหรับมือถือ (แตะหน้าจอ 2 ครั้ง)
            icon.addEventListener('touchend', (e) => {
                e.preventDefault(); 
                let now = Date.now();
                if (now - lastTap < 400) { triggerApp(icon.dataset.exec); }
                lastTap = now;
            });

            // สำหรับ PC (ดับเบิ้ลคลิกเมาส์)
            icon.addEventListener('dblclick', (e) => {
                e.preventDefault();
                triggerApp(icon.dataset.exec);
            });
        });

        // 2. ระบบลากหน้าต่าง (Drag)
        const startDrag = (e) => {
            const clientX = e.touches ? e.touches[0].clientX : e.clientX; 
            const clientY = e.touches ? e.touches[0].clientY : e.clientY;
            const header = e.target.closest('.win-header');
            if(header && !header.parentElement.dataset.locked) {
                const win = header.parentElement; 
                this.focusWindow(win.id); 
                this.dragState.win = win;
                const rect = win.getBoundingClientRect();
                this.dragState.offsetX = clientX - rect.left; 
                this.dragState.offsetY = clientY - rect.top;
                
                // แก้หน้าต่างกระตุกตอนเริ่มลาก
                if(win.style.transform.includes('translate')) {
                    win.style.transform = 'none';
                    win.style.left = rect.left + 'px';
                    win.style.top = rect.top + 'px';
                }
            }
        };
        const doDrag = (e) => {
            if(this.dragState.win) {
                const clientX = e.touches ? e.touches[0].clientX : e.clientX; 
                const clientY = e.touches ? e.touches[0].clientY : e.clientY;
                this.dragState.win.style.left = (clientX - this.dragState.offsetX) + 'px'; 
                this.dragState.win.style.top = (clientY - this.dragState.offsetY) + 'px';
                if(e.touches) e.preventDefault(); 
            }
        };
        const stopDrag = () => { this.dragState.win = null; };

        document.addEventListener('mousedown', startDrag); document.addEventListener('touchstart', startDrag, {passive: false});
        document.addEventListener('mousemove', doDrag); document.addEventListener('touchmove', doDrag, {passive: false});
        document.addEventListener('mouseup', stopDrag); document.addEventListener('touchend', stopDrag);

        // 3. ปุ่ม Start Menu บน Taskbar
        document.getElementById('taskbar-start').addEventListener('click', () => {
            if (director.phase >= 3) { 
                audio.playError(); utils.flashScreen(); 
                this.spawnWindow('FATAL', 'THERE IS NO START. ONLY END.', 'warn', { locked: true }); 
            } else { 
                audio.playClick(); 
                this.spawnWindow(i18n.t('task_start'), 'System functioning. Return to tasks.', 'normal'); 
            }
        });
    }

    spawnWindow(title, contentHTML, type = 'normal', opts = {}) {
        const id = 'win_' + Math.random().toString(36).substr(2, 9);
        const win = document.createElement('div'); win.id = id; win.className = `os-window ${type}`;
        if(opts.locked) win.dataset.locked = "true";

        // ALL WINDOWS SPAWN IN EXACT CENTER FIRST
        win.style.top = '50%'; win.style.left = '50%'; win.style.transform = 'translate(-50%, -50%)';

        const header = document.createElement('div'); header.className = 'win-header';
        const titleArea = document.createElement('div'); titleArea.className = 'win-title'; titleArea.innerHTML = `<span>${title}</span>`; header.appendChild(titleArea);
        
        if(!opts.locked) {
            const controls = document.createElement('div'); controls.className = 'win-controls';
            const closeBtn = document.createElement('div'); closeBtn.className = 'win-btn close'; closeBtn.innerText = 'X';
            closeBtn.ontouchend = closeBtn.onclick = (e) => { e.preventDefault(); this.closeWindow(id); };
            controls.appendChild(closeBtn); header.appendChild(controls);
        }

        const content = document.createElement('div'); content.className = `win-content ${opts.isTerm ? 'term-style' : ''}`; content.innerHTML = contentHTML;
        
        if(opts.buttons) {
            const actions = document.createElement('div'); actions.className = 'win-actions';
            opts.buttons.forEach(b => {
                const btn = document.createElement('button'); btn.className = 'os-btn'; btn.innerText = b.text;
                btn.ontouchend = btn.onclick = (e) => { e.preventDefault(); audio.playClick(); b.onClick(id); };
                actions.appendChild(btn);
            });
            content.appendChild(actions);
        }

        win.appendChild(header); win.appendChild(content); this.container.appendChild(win);
        const task = document.createElement('div'); task.className = 'task-item'; task.id = 'task_' + id; task.innerText = title;
        task.onclick = () => this.focusWindow(id); this.taskbar.appendChild(task);
        this.windows.set(id, { el: win, task: task, type: type }); this.focusWindow(id);
        if (opts.isTerm) this.termElement = content; return id;
    }

    updateWindow(id, contentHTML, buttons) {
        const win = this.windows.get(id); if (!win) return;
        const content = win.el.querySelector('.win-content'); content.innerHTML = contentHTML;
        if (buttons) {
            const actions = document.createElement('div'); actions.className = 'win-actions';
            buttons.forEach(b => {
                const btn = document.createElement('button'); btn.className = 'os-btn'; btn.innerText = b.text;
                btn.ontouchend = btn.onclick = (e) => { e.preventDefault(); audio.playClick(); b.onClick(id); };
                actions.appendChild(btn);
            });
            content.appendChild(actions);
        }
    }

    closeWindow(id) {
        if(!this.windows.has(id)) return; audio.playClick(); const obj = this.windows.get(id); obj.el.classList.add('closing');
        setTimeout(() => { obj.el.remove(); obj.task.remove(); this.windows.delete(id); if(this.termElement === obj.el.querySelector('.term-style')) this.termElement = null; }, 150);
    }
    focusWindow(id) {
        this.zIndex++; this.windows.forEach((val, key) => { val.task.classList.remove('active'); if(key === id) { val.el.style.zIndex = this.zIndex; val.task.classList.add('active'); }});
    }

    spawnReadme() {
        if(director.phase === 1) this.spawnWindow(i18n.t('rm_title'), i18n.t('rm_txt'));
        else { audio.playError(); this.spawnWindow(i18n.t('rm_title'), utils.corruptText(i18n.t('rm_warn')), 'warn'); }
    }
    spawnLogs() {
        if(director.phase < 3) this.spawnWindow(i18n.t('log_title'), i18n.t('log_txt'));
        else { audio.playError(); utils.flashScreen(); this.spawnWindow(utils.corruptText(i18n.t('log_title')), i18n.t('log_warn'), 'warn', { locked: true }); }
    }
    spawnTrash() {
        if(director.phase >= 2) { audio.playError(); this.spawnWindow(i18n.t('trash_title'), i18n.t('trash_warn'), 'warn'); }
        else this.spawnWindow(i18n.t('trash_title'), i18n.t('trash_txt'));
    }
    spawnTerminal() {
        if(this.termElement && document.body.contains(this.termElement)) return;
        this.spawnWindow(i18n.t('icon_term'), '', 'normal', { isTerm: true });
        this.printTerm(i18n.t('term_init')); this.printTerm(i18n.t('term_wait'));
        if (director.phase >= 2) setTimeout(() => this.printTerm(i18n.t('term_warn')), 1000);
    }
    async printTerm(text) {
        if(!this.termElement) return; const line = document.createElement('div'); this.termElement.appendChild(line);
        if (settings.textSpeed === 0) { line.innerHTML = `> ${text}`; this.termElement.scrollTop = this.termElement.scrollHeight; return; }
        let currentText = `> `; let isHTMLTag = false;
        for (let i = 0; i < text.length; i++) {
            currentText += text[i]; line.innerHTML = currentText; this.termElement.scrollTop = this.termElement.scrollHeight;
            if (text[i] === '<') isHTMLTag = true; if (text[i] === '>') isHTMLTag = false;
            if (!isHTMLTag) await utils.wait(settings.textSpeed);
        }
    }
}

